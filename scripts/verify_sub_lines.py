from PIL import Image, ImageDraw, ImageFont

fnt = ImageFont.truetype('fonts/Pacifico-Regular.ttf', 100)
img = Image.new('RGB', (100, 100))
draw = ImageDraw.Draw(img)

# Phrases designed specifically for 100pt font (max width < 880px):
dialogues = [
    # 00:00.20 - 00:03.20 (Закончив оформление их костюмчиков)
    ("0:00:00.20", "0:00:03.20", "Закончив\\nоформление печенья,"),
    # 00:03.20 - 00:06.40 (я взяла три листка для записей)
    ("0:00:03.20", "0:00:06.40", "я взяла три листка\\nдля записей"),
    # 00:06.40 - 00:10.00 (и маркером написала название печенья на каждом)
    ("0:00:06.40", "0:00:10.00", "и маркером написала\\nназвание на каждом:"),
    # 00:10.15 - 00:12.60 («Рыжие сдобные зомби»)
    ("0:00:10.15", "0:00:12.60", "«Рыжие сдобные\\nзомби»."),
    # 00:12.60 - 00:15.90 (Это название очень подходило моему состоянию зомби)
    ("0:00:12.60", "0:00:15.90", "Это название подходило\\nмоему состоянию,"),
    # 00:15.90 - 00:18.30 (в котором я находилась сегодня весь день)
    ("0:00:15.90", "0:00:18.30", "в котором я была\\nсегодня весь день,"),
    # 00:18.30 - 00:20.15 (в каком буду завтра, как и все последние месяцы)
    ("0:00:18.30", "0:00:20.15", "в каком буду завтра\\nи все эти месяцы."),
    # 00:20.30 - 00:22.60 (Пять часов, четыре чашки кофе)
    ("0:00:20.30", "0:00:22.60", "Пять часов,\\nчетыре чашки кофе,"),
    # 00:22.60 - 00:25.00 (две страницы английского текста и завтрак был готов)
    ("0:00:22.60", "0:00:25.00", "две страницы эссе —\\nи завтрак готов!"),
    # 00:25.10 - 00:28.40 (А я готова переодеться, чтобы идти в школу)
    ("0:00:25.10", "0:00:28.40", "А я готова\\nидти в школу,"),
    # 00:28.40 - 00:33.10 (натянув свою обычную толстовку и джинсы и распустив свои длинные темные волосы)
    ("0:00:28.40", "0:00:30.80", "натянув толстовку\\nи джинсы,"),
    ("0:00:30.80", "0:00:33.10", "и распустив\\nдлинные волосы."),
    # 00:33.30 - 00:36.80 (Эсми уже уехала на работу)
    ("0:00:33.30", "0:00:36.80", "Эсми уже уехала\\nна работу"),
    # 00:36.80 - 00:40.50 (и прихватила с собой моих Рыжих сдобных зомби)
    ("0:00:36.80", "0:00:40.50", "и прихватила с собой\\n«Рыжих зомби»,"),
    # 00:40.50 - 00:43.50 (улыбнувшись мне при этом кривой улыбкой, когда увидела мое новое творение)
    ("0:00:40.50", "0:00:43.50", "улыбнувшись моему\\nновому творению."),
]

all_good = True
for st, et, txt in dialogues:
    lines = txt.split("\\n")
    for l in lines:
        bbox = draw.textbbox((0, 0), l, font=fnt)
        w = bbox[2] - bbox[0]
        if w > 880:
            print(f"TOO WIDE: {w}px -> {l}")
            all_good = False

if all_good:
    print("All lines are perfectly within the 880px safe area at 100pt!")
