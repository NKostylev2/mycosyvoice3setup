from __future__ import annotations

import json
import sqlite3
from collections import defaultdict
from datetime import datetime
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / "database" / "dubbing.db"

EVENT_TYPE = "source_reported_air_date"


def normalize_date(value: str | None) -> str | None:
    """Convert supported date formats to YYYY-MM-DD."""

    if not value:
        return None

    value = value.strip()

    if not value:
        return None

    formats = (
        "%Y-%m-%d",
        "%B %d, %Y",
        "%b %d, %Y",
        "%d %B %Y",
        "%d %b %Y",
        "%Y/%m/%d",
        "%d.%m.%Y",
        "%m/%d/%Y",
    )

    for fmt in formats:
        try:
            return datetime.strptime(value, fmt).date().isoformat()
        except ValueError:
            continue

    return None


def main() -> None:
    conn = sqlite3.connect(DB)
    conn.execute("PRAGMA foreign_keys = ON")

    try:
        conn.execute("BEGIN")

        # --------------------------------------------------------
        # Remove only data generated by this script.
        # Source records remain untouched.
        # --------------------------------------------------------

        conn.execute(
            f"""
            DELETE FROM broadcast_events
            WHERE event_type = '{EVENT_TYPE}'
            """
        )

        conn.execute(
            """
            DELETE FROM knowledge_conflicts
            WHERE entity_type = 'episode'
              AND field_name = 'air_date'
            """
        )

        # --------------------------------------------------------
        # Load source records
        # --------------------------------------------------------

        query = """
        SELECT
            e.id,
            e.episode_id,
            e.absolute_number,
            e.title_original,

            r.id,
            r.source_record_id,
            r.air_date_raw,
            s.source_name,
            r.source_url,
            r.confidence

        FROM episodes AS e

        JOIN episode_source_records AS r
            ON r.episode_id = e.id

        JOIN sources AS s
            ON s.id = r.source_id

        ORDER BY
            e.absolute_number,
            s.source_name,
            r.id
        """

        rows = conn.execute(query).fetchall()

        # episode_id -> source_name -> records
        by_episode = defaultdict(lambda: defaultdict(list))

        for row in rows:
            (
                db_episode_id,
                episode_id,
                absolute_number,
                title,
                source_record_db_id,
                source_record_id,
                air_date_raw,
                source_name,
                source_url,
                confidence,
            ) = row

            by_episode[episode_id][source_name].append(
                {
                    "db_episode_id": db_episode_id,
                    "absolute_number": absolute_number,
                    "title": title,
                    "source_record_db_id": source_record_db_id,
                    "source_record_id": source_record_id,
                    "air_date": air_date_raw,
                    "source": source_name,
                    "source_url": source_url,
                    "confidence": confidence,
                }
            )

        event_count = 0
        conflict_count = 0
        invalid_date_count = 0

        # --------------------------------------------------------
        # Process every physical episode
        # --------------------------------------------------------

        for episode_id, sources in by_episode.items():

            episode_db_id = next(
                record["db_episode_id"]
                for records in sources.values()
                for record in records
            )

            # ----------------------------------------------------
            # BROADCAST EVENTS
            # ----------------------------------------------------

            for source_name, records in sources.items():

                source_row = conn.execute(
                    """
                    SELECT id
                    FROM sources
                    WHERE source_name = ?
                    LIMIT 1
                    """,
                    (source_name,),
                ).fetchone()

                if source_row is None:
                    raise RuntimeError(
                        f"Source not found in database: {source_name}"
                    )

                source_db_id = source_row[0]

                for record in records:

                    raw_air_date = record["air_date"]

                    if not raw_air_date:
                        continue

                    normalized_air_date = normalize_date(raw_air_date)

                    if not normalized_air_date:
                        invalid_date_count += 1
                        continue

                    metadata = {
                        "episode_id": episode_id,
                        "source_record_id": record["source_record_id"],
                        "source_url": record["source_url"],
                        "origin": "episode_source_records",
                        "raw_air_date": raw_air_date,
                    }

                    conn.execute(
                        """
                        INSERT INTO broadcast_events (
                            episode_id,
                            broadcast_date,
                            country,
                            region,
                            network,
                            language,
                            event_type,
                            source_id,
                            confidence,
                            notes
                        )
                        VALUES (
                            ?,
                            ?,
                            NULL,
                            NULL,
                            NULL,
                            NULL,
                            ?,
                            ?,
                            ?,
                            ?
                        )
                        """,
                        (
                            episode_db_id,
                            normalized_air_date,
                            EVENT_TYPE,
                            source_db_id,
                            record["confidence"],
                            json.dumps(
                                metadata,
                                ensure_ascii=False,
                            ),
                        ),
                    )

                    event_count += 1

            # ----------------------------------------------------
            # NORMALIZED DATES PER SOURCE
            # ----------------------------------------------------

            dated_sources: dict[str, list[str]] = {}

            for source_name, records in sources.items():

                normalized_dates = set()

                for record in records:

                    raw_air_date = record["air_date"]

                    if not raw_air_date:
                        continue

                    normalized = normalize_date(raw_air_date)

                    if normalized is None:
                        continue

                    normalized_dates.add(normalized)

                if normalized_dates:
                    dated_sources[source_name] = sorted(
                        normalized_dates
                    )

            # ----------------------------------------------------
            # SOURCE-TO-SOURCE CONFLICTS
            # ----------------------------------------------------

            source_names = sorted(dated_sources.keys())

            for i, source_a in enumerate(source_names):

                for source_b in source_names[i + 1:]:

                    dates_a = dated_sources[source_a]
                    dates_b = dated_sources[source_b]

                    # Same date exists in both sources:
                    # no conflict.
                    if set(dates_a).intersection(dates_b):
                        continue

                    conn.execute(
                        """
                        INSERT INTO knowledge_conflicts (
                            entity_type,
                            entity_id,
                            field_name,
                            source_a,
                            value_a,
                            source_b,
                            value_b,
                            resolution,
                            resolved_value,
                            status
                        )
                        VALUES (
                            'episode',
                            ?,
                            'air_date',
                            ?,
                            ?,
                            ?,
                            ?,
                            NULL,
                            NULL,
                            'open'
                        )
                        """,
                        (
                            episode_id,
                            source_a,
                            json.dumps(
                                dates_a,
                                ensure_ascii=False,
                            ),
                            source_b,
                            json.dumps(
                                dates_b,
                                ensure_ascii=False,
                            ),
                        ),
                    )

                    conflict_count += 1

        conn.commit()

        # --------------------------------------------------------
        # VALIDATION
        # --------------------------------------------------------

        episode_count = conn.execute(
            """
            SELECT COUNT(*)
            FROM episodes
            """
        ).fetchone()[0]

        event_count_db = conn.execute(
            """
            SELECT COUNT(*)
            FROM broadcast_events
            WHERE event_type = ?
            """,
            (EVENT_TYPE,),
        ).fetchone()[0]

        conflict_count_db = conn.execute(
            """
            SELECT COUNT(*)
            FROM knowledge_conflicts
            WHERE entity_type = 'episode'
              AND field_name = 'air_date'
              AND status = 'open'
            """
        ).fetchone()[0]

        print("[OK] Broadcast events built")
        print()
        print(f"Episodes                  : {episode_count}")
        print(f"Broadcast events          : {event_count_db}")
        print(f"Air-date conflicts        : {conflict_count_db}")
        print(f"Invalid/unparsed dates    : {invalid_date_count}")
        print()

        print("Conflict count by pair:")

        pairs = conn.execute(
            """
            SELECT
                source_a,
                source_b,
                COUNT(*)
            FROM knowledge_conflicts
            WHERE entity_type = 'episode'
              AND field_name = 'air_date'
              AND status = 'open'
            GROUP BY
                source_a,
                source_b
            ORDER BY
                source_a,
                source_b
            """
        ).fetchall()

        if not pairs:
            print("  none")
        else:
            for source_a, source_b, count in pairs:
                print(
                    f"  {source_a:12s} <-> "
                    f"{source_b:12s}: {count}"
                )

    except Exception:
        conn.rollback()
        raise

    finally:
        conn.close()


if __name__ == "__main__":
    main()